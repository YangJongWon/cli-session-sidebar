const dictionaries: Record<Language, Record<MessageKey, string>> = { ko, ja, zh, en };

let active: Language = 'ko';

export function isUiLanguage(value: unknown): value is UiLanguage {
  return typeof value === 'string' && (UI_LANGUAGES as readonly string[]).includes(value);
}

export function resolveLanguage(setting: UiLanguage, locale: string): Language {
  if (setting !== 'auto') return setting;
  const tag = locale.toLowerCase();
  if (tag.startsWith('ko')) return 'ko';
  if (tag.startsWith('ja')) return 'ja';
  if (tag.startsWith('zh')) return 'zh';
  if (tag.startsWith('en')) return 'en';
  return 'en';
}

export function currentLanguage(): Language {
  return active;
}

export function setLanguage(language: Language): void {
  active = language;
}

export function matchesMessage(text: string, key: MessageKey): boolean {
  const sample = text.split('\n')[0] ?? '';
  return (Object.keys(dictionaries) as Language[]).some((language) => {
    const phrase = dictionaries[language][key].split('{')[0].trim();
    return phrase.length > 0 && sample.includes(phrase);
  });
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[active][key] ?? dictionaries.ko[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
